import { parseState } from '../build/blockstate.js';
import type { VoxelGrid } from '../build/voxel-grid.js';
import { nbt, writeGzipNbt, type Tag } from './nbt.js';
import { signBlockEntityData } from './sign.js';

/**
 * Litematica schematic, format Version 6 / SubVersion 1 (what litemapy reads
 * and writes; Litematica upgrades it on load).
 */
export const LITEMATIC_VERSION = 6;
export const LITEMATIC_SUBVERSION = 1;

export function bitsFor(paletteLength: number): number {
  return Math.max(2, Math.ceil(Math.log2(paletteLength)));
}

/**
 * Packs fixed-width values into big-endian 64-bit longs, LSB first, with
 * entries allowed to span two longs (Litematica's LitematicaBitArray layout).
 */
export class BitPacker {
  private lo = 0;
  private hi = 0;
  private bit = 0;
  private buf: Uint8Array;
  private pos = 0;
  readonly chunks: Uint8Array[] = [];

  constructor(private readonly nbits: number, chunkBytes = 1 << 18) {
    if (nbits < 1 || nbits > 16) throw new RangeError('nbits must be 1..16');
    this.buf = new Uint8Array(chunkBytes);
  }

  put(v: number): void {
    const n = this.nbits;
    let bit = this.bit;
    if (bit < 32) {
      this.lo = (this.lo | (v << bit)) >>> 0;
      if (bit + n > 32) this.hi = (this.hi | (v >>> (32 - bit))) >>> 0;
    } else {
      this.hi = (this.hi | (v << (bit - 32))) >>> 0;
    }
    bit += n;
    if (bit >= 64) {
      this.emit();
      bit -= 64;
      this.lo = bit > 0 ? v >>> (n - bit) : 0;
      this.hi = 0;
    }
    this.bit = bit;
  }

  private emit(): void {
    if (this.pos + 8 > this.buf.length) {
      this.chunks.push(this.buf.subarray(0, this.pos));
      this.buf = new Uint8Array(this.buf.length);
      this.pos = 0;
    }
    const b = this.buf;
    const p = this.pos;
    const hi = this.hi;
    const lo = this.lo;
    b[p] = hi >>> 24; b[p + 1] = hi >>> 16; b[p + 2] = hi >>> 8; b[p + 3] = hi;
    b[p + 4] = lo >>> 24; b[p + 5] = lo >>> 16; b[p + 6] = lo >>> 8; b[p + 7] = lo;
    this.pos = p + 8;
  }

  /** Flushes the partial last long and returns pending chunks. */
  finish(): Uint8Array[] {
    if (this.bit > 0) this.emit();
    this.bit = 0;
    return this.drain(true);
  }

  drain(all = false): Uint8Array[] {
    if (all && this.pos) {
      this.chunks.push(this.buf.subarray(0, this.pos));
      this.buf = new Uint8Array(this.buf.length);
      this.pos = 0;
    }
    return this.chunks.splice(0);
  }
}

export function longCount(volume: number, nbits: number): number {
  return Math.ceil((volume * nbits) / 64);
}

function* blockStates(grid: VoxelGrid, height: number, nbits: number): Generator<Uint8Array> {
  const packer = new BitPacker(nbits);
  const row = new Uint16Array(grid.width);
  for (let y = 0; y < height; y++) {
    for (let z = 0; z < grid.length; z++) {
      grid.row(y, z, row);
      for (let x = 0; x < grid.width; x++) packer.put(row[x]!);
      yield* packer.drain();
    }
  }
  yield* packer.finish();
}

export interface LitematicMeta {
  name: string;
  author: string;
  /** Epoch ms (HEAD commit time). */
  date: number;
  dataVersion: number;
  description?: string;
}

export function litematicTag(grid: VoxelGrid, meta: LitematicMeta): Tag {
  const height = Math.max(1, grid.topY());
  const volume = grid.width * height * grid.length;
  const nbits = bitsFor(grid.palette.length);
  const counts = grid.counts();
  let totalBlocks = 0;
  for (let i = 1; i < counts.length; i++) totalBlocks += counts[i]!;
  const size = nbt.compound({ x: nbt.int(grid.width), y: nbt.int(height), z: nbt.int(grid.length) });
  const palette = grid.palette.map((state) => {
    const p = parseState(state);
    const entries = Object.entries(p.properties);
    return nbt.compound({
      Name: nbt.string(p.name),
      ...(entries.length ? { Properties: nbt.compound(Object.fromEntries(entries.map(([k, v]) => [k, nbt.string(v)]))) } : {}),
    });
  });
  const tiles = grid.blockEntities
    .filter((e) => e.y < height)
    .map((e) => {
      const data = signBlockEntityData(e.lines, meta.dataVersion);
      if (data.type !== 'compound') throw new Error('unreachable');
      return nbt.compound({ x: nbt.int(e.x), y: nbt.int(e.y), z: nbt.int(e.z), id: nbt.string(e.id), ...data.value });
    });
  return nbt.compound({
    MinecraftDataVersion: nbt.int(meta.dataVersion),
    Version: nbt.int(LITEMATIC_VERSION),
    SubVersion: nbt.int(LITEMATIC_SUBVERSION),
    Metadata: nbt.compound({
      EnclosingSize: size,
      Author: nbt.string(meta.author),
      Description: nbt.string(meta.description ?? 'Generated by repoville'),
      Name: nbt.string(meta.name),
      RegionCount: nbt.int(1),
      TimeCreated: nbt.long(meta.date),
      TimeModified: nbt.long(meta.date),
      TotalBlocks: nbt.int(totalBlocks),
      TotalVolume: nbt.int(volume),
    }),
    Regions: nbt.compound({
      [meta.name]: nbt.compound({
        Position: nbt.compound({ x: nbt.int(0), y: nbt.int(0), z: nbt.int(0) }),
        Size: size,
        BlockStatePalette: nbt.list('compound', palette),
        Entities: nbt.list('compound', []),
        TileEntities: nbt.list('compound', tiles),
        PendingBlockTicks: nbt.list('compound', []),
        PendingFluidTicks: nbt.list('compound', []),
        BlockStates: { type: 'stream', of: 'longArray', length: longCount(volume, nbits), chunks: () => blockStates(grid, height, nbits) },
      }),
    }),
  });
}

export async function writeLitematic(file: string, grid: VoxelGrid, meta: LitematicMeta): Promise<void> {
  await writeGzipNbt(file, '', litematicTag(grid, meta));
}
